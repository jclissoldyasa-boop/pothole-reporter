// Builds src/councils.gen.js (the council keys the server accepts) from the app's councils.js, using the app's own
// coreName(), so the two can't drift apart. Run after changing councils.js or coreName(): node sync-councils.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const here = p => new URL(p, import.meta.url);
const app = readFileSync(here("../app.js"), "utf8");
const fn = app.match(/function coreName\(n\)\{.*\}/);
if (!fn) throw new Error("coreName() not found in app.js");
const ctx = { window: {} };
vm.runInNewContext(readFileSync(here("../councils.js"), "utf8") + "\n" + fn[0] + "\nthis.coreName=coreName;", ctx);

const STATES = { vic: "VIC", nsw: "NSW", qld: "QLD", sa: "SA", wa: "WA", tas: "TAS", nt: "NT" };
const keys = [];
for (const [st, up] of Object.entries(STATES)) {
  const list = ctx.window[up + "_COUNCILS"] || [];
  const ks = list.map(([name]) => st + ":" + ctx.coreName(name));
  if (new Set(ks).size !== ks.length) throw new Error("two " + up + " councils share a key");
  keys.push(...ks);
}
writeFileSync(here("src/councils.gen.js"),
  "// Generated by sync-councils.mjs from councils.js. Don't edit by hand.\n" +
  "// Every council the app has contacts for, as \"state:core name\" (matches coreName() in app.js).\n" +
  "export const COUNCIL_KEYS = " + JSON.stringify(keys) + ";\n");
console.log(keys.length + " council keys written");
